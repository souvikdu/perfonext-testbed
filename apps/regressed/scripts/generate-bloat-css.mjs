// B7 fixture. Emits a large, deterministic CSS file so the regressed build produces
// a noticeably heavier CSS asset than baseline. CSS assets get pure-hash filenames
// (no `-<contenthash>` suffix), which is the branch of build-mcp's chunk matcher
// that must NOT be hash-normalised.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, '../src/app/bloat.css');

const PALETTE = [
  '#6ee7b7',
  '#7dd3fc',
  '#fca5a5',
  '#fcd34d',
  '#c4b5fd',
  '#f9a8d4',
  '#a7f3d0',
  '#fdba74',
];
const RULES = 2400;

let out = '/* GENERATED by scripts/generate-bloat-css.mjs — do not edit. */\n';
for (let i = 0; i < RULES; i += 1) {
  const colour = PALETTE[i % PALETTE.length];
  out += `.tb-u-${i} {\n`;
  out += `  color: ${colour};\n`;
  out += `  border-color: ${colour};\n`;
  out += `  margin: ${i % 24}px ${(i * 3) % 32}px;\n`;
  out += `  padding: ${i % 16}px;\n`;
  out += `  letter-spacing: ${(i % 9) / 100}em;\n`;
  out += `  box-shadow: 0 ${i % 6}px ${i % 18}px rgba(0, 0, 0, 0.${(i % 8) + 1});\n`;
  out += `}\n`;
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out, 'utf8');
console.log(`wrote ${target} (${out.length} bytes, ${RULES} rules)`);
